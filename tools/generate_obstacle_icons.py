#!/usr/bin/env python3

import argparse
import re
from dataclasses import dataclass
from pathlib import Path

from PIL import Image


ICON_NAME_PATTERN = re.compile(r"^(\d{2})_([a-z0-9_]+)\.png$")
ICON_SIZE = (24, 24)


@dataclass(frozen=True)
class IconSource:
    number: int
    stem: str
    enabled_path: Path
    disabled_path: Path
    enabled_rgba: bytes
    disabled_rgba: bytes


def collect_paths(directory: Path) -> dict[int, tuple[str, Path]]:
    paths: dict[int, tuple[str, Path]] = {}
    for path in sorted(directory.glob("*.png")):
        match = ICON_NAME_PATTERN.fullmatch(path.name)
        if not match:
            raise ValueError(
                f"Icon name must match NN_lowercase_name.png: {path}"
            )

        number = int(match.group(1))
        stem = match.group(2)
        if number < 1:
            raise ValueError(f"Icon number must start at 01: {path}")
        if number in paths:
            raise ValueError(f"Duplicate icon number {number:02d} in {directory}")
        paths[number] = (stem, path)
    return paths


def load_rgba(path: Path) -> bytes:
    with Image.open(path) as image:
        if image.size != ICON_SIZE:
            raise ValueError(
                f"Icon must be {ICON_SIZE[0]}x{ICON_SIZE[1]} pixels: "
                f"{path} is {image.size[0]}x{image.size[1]}"
            )
        if image.mode != "RGBA":
            raise ValueError(f"Icon must be an RGBA PNG: {path} uses {image.mode}")
        return image.tobytes()


def collect_icons(root: Path) -> list[IconSource]:
    enabled = collect_paths(root / "enabled")
    disabled = collect_paths(root / "disabled")
    if enabled.keys() != disabled.keys():
        missing_disabled = sorted(enabled.keys() - disabled.keys())
        missing_enabled = sorted(disabled.keys() - enabled.keys())
        raise ValueError(
            "Enabled/disabled icon numbers must match. "
            f"Missing disabled: {missing_disabled}; missing enabled: {missing_enabled}"
        )

    icons: list[IconSource] = []
    for number in sorted(enabled):
        enabled_stem, enabled_path = enabled[number]
        disabled_stem, disabled_path = disabled[number]
        if enabled_stem != disabled_stem:
            raise ValueError(
                f"Icon {number:02d} names differ: "
                f"{enabled_path.name} vs {disabled_path.name}"
            )
        icons.append(
            IconSource(
                number=number,
                stem=enabled_stem,
                enabled_path=enabled_path,
                disabled_path=disabled_path,
                enabled_rgba=load_rgba(enabled_path),
                disabled_rgba=load_rgba(disabled_path),
            )
        )
    return icons


def format_byte_array(name: str, data: bytes) -> str:
    lines = [f"    constexpr unsigned char {name}[] =", "    {"]
    for offset in range(0, len(data), 16):
        chunk = data[offset : offset + 16]
        values = ", ".join(f"0x{value:02X}" for value in chunk)
        lines.append(f"        {values},")
    lines.append("    };")
    return "\n".join(lines)


def generate_source(icons: list[IconSource]) -> str:
    arrays: list[str] = []
    rows: list[str] = []
    for icon in icons:
        suffix = f"Button{icon.number:02d}"
        enabled_name = f"kEnabled{suffix}"
        disabled_name = f"kDisabled{suffix}"
        arrays.append(format_byte_array(enabled_name, icon.enabled_rgba))
        arrays.append(format_byte_array(disabled_name, icon.disabled_rgba))
        rows.append(
            "        { "
            f"{icon.number - 1}, "
            f"{{ 24, 24, {enabled_name} }}, "
            f"{{ 24, 24, {disabled_name} }} "
            "},"
        )

    return "\n".join(
        [
            '#include "pch.h"',
            '#include "obstacle_icon_data.h"',
            "",
            "// Generated by tools/generate_obstacle_icons.py from user-created PNGs.",
            "namespace",
            "{",
            *arrays,
            "",
            "    struct ObstacleIconPair",
            "    {",
            "        int buttonIndex;",
            "        ObstacleIconData enabled;",
            "        ObstacleIconData disabled;",
            "    };",
            "",
            "    constexpr ObstacleIconPair kObstacleIcons[] =",
            "    {",
            *rows,
            "    };",
            "}",
            "",
            "const ObstacleIconData* ObstacleIconForButton(int buttonIndex, bool enabled)",
            "{",
            "    for (const ObstacleIconPair& pair : kObstacleIcons)",
            "    {",
            "        if (pair.buttonIndex == buttonIndex)",
            "            return enabled ? &pair.enabled : &pair.disabled;",
            "    }",
            "    return nullptr;",
            "}",
            "",
        ]
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--icons",
        type=Path,
        default=Path("plugin/resources/obstacle_icons"),
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("plugin/obstacle_icon_data.cpp"),
    )
    args = parser.parse_args()

    icons = collect_icons(args.icons)
    if not icons:
        raise ValueError(f"No obstacle icons found under {args.icons}")

    args.output.write_text(generate_source(icons), encoding="ascii", newline="\n")
    print(f"Generated {args.output} with {len(icons)} enabled/disabled icon pairs.")


if __name__ == "__main__":
    main()
