#!/usr/bin/env python3

import argparse
import re
from dataclasses import dataclass
from pathlib import Path

from PIL import Image


ICON_NAME_PATTERN = re.compile(r"^(\d{2})_([a-z0-9_]+)\.png$")
ICON_SIZE = (24, 24)
PREVIEW_SIZE = (160, 160)
PREVIEW_RESOURCE_BASE = 5000


@dataclass(frozen=True)
class IconSource:
    number: int
    stem: str
    enabled_path: Path
    disabled_path: Path
    enabled_rgba: bytes
    disabled_rgba: bytes


def collect_paths(directory: Path) -> dict[int, tuple[str, Path]]:
    paths: dict[int, tuple[str, Path]] = {}
    for path in sorted(directory.glob("*.png")):
        match = ICON_NAME_PATTERN.fullmatch(path.name)
        if not match:
            raise ValueError(
                f"Icon name must match NN_lowercase_name.png: {path}"
            )

        number = int(match.group(1))
        stem = match.group(2)
        if number < 1:
            raise ValueError(f"Icon number must start at 01: {path}")
        if number in paths:
            raise ValueError(f"Duplicate icon number {number:02d} in {directory}")
        paths[number] = (stem, path)
    return paths


def load_rgba(path: Path, expected_size: tuple[int, int]) -> bytes:
    with Image.open(path) as image:
        if image.size != expected_size:
            raise ValueError(
                f"Icon must be {expected_size[0]}x{expected_size[1]} pixels: "
                f"{path} is {image.size[0]}x{image.size[1]}"
            )
        if image.mode != "RGBA":
            raise ValueError(f"Icon must be an RGBA PNG: {path} uses {image.mode}")
        return image.tobytes()


def collect_icons(root: Path) -> list[IconSource]:
    enabled = collect_paths(root / "enabled")
    disabled = collect_paths(root / "disabled")
    if enabled.keys() != disabled.keys():
        missing_disabled = sorted(enabled.keys() - disabled.keys())
        missing_enabled = sorted(disabled.keys() - enabled.keys())
        raise ValueError(
            "Enabled/disabled icon numbers must match. "
            f"Missing disabled: {missing_disabled}; missing enabled: {missing_enabled}"
        )

    icons: list[IconSource] = []
    for number in sorted(enabled):
        enabled_stem, enabled_path = enabled[number]
        disabled_stem, disabled_path = disabled[number]
        if enabled_stem != disabled_stem:
            raise ValueError(
                f"Icon {number:02d} names differ: "
                f"{enabled_path.name} vs {disabled_path.name}"
            )
        icons.append(
            IconSource(
                number=number,
                stem=enabled_stem,
                enabled_path=enabled_path,
                disabled_path=disabled_path,
                enabled_rgba=load_rgba(enabled_path, ICON_SIZE),
                disabled_rgba=load_rgba(disabled_path, ICON_SIZE),
            )
        )
    return icons


def collect_previews(root: Path, icons: list[IconSource]) -> dict[int, Path]:
    previews = collect_paths(root / "preview")
    icon_names = {icon.number: icon.stem for icon in icons}
    for number, (stem, path) in previews.items():
        if number not in icon_names:
            raise ValueError(f"Preview has no matching enabled icon: {path}")
        if stem != icon_names[number]:
            raise ValueError(
                f"Preview {number:02d} name differs from enabled icon: "
                f"{path.name} vs {number:02d}_{icon_names[number]}.png"
            )
        load_rgba(path, PREVIEW_SIZE)
    return {number: path for number, (_, path) in previews.items()}


def format_byte_array(name: str, data: bytes) -> str:
    lines = [f"    constexpr unsigned char {name}[] =", "    {"]
    for offset in range(0, len(data), 16):
        chunk = data[offset : offset + 16]
        values = ", ".join(f"0x{value:02X}" for value in chunk)
        lines.append(f"        {values},")
    lines.append("    };")
    return "\n".join(lines)


def generate_source(icons: list[IconSource], previews: dict[int, Path]) -> str:
    arrays: list[str] = []
    rows: list[str] = []
    for icon in icons:
        suffix = f"Button{icon.number:02d}"
        enabled_name = f"kEnabled{suffix}"
        disabled_name = f"kDisabled{suffix}"
        arrays.append(format_byte_array(enabled_name, icon.enabled_rgba))
        arrays.append(format_byte_array(disabled_name, icon.disabled_rgba))
        rows.append(
            "        { "
            f"{icon.number - 1}, "
            f"{{ 24, 24, {enabled_name} }}, "
            f"{{ 24, 24, {disabled_name} }} "
            "},"
        )

    preview_rows = [
        f"        {{ {number - 1}, {PREVIEW_RESOURCE_BASE + number} }},"
        for number in sorted(previews)
    ]

    return "\n".join(
        [
            '#include "pch.h"',
            '#include "obstacle_icon_data.h"',
            "",
            "// Generated by tools/generate_obstacle_icons.py from user-created PNGs.",
            "namespace",
            "{",
            *arrays,
            "",
            "    struct ObstacleIconPair",
            "    {",
            "        int buttonIndex;",
            "        ObstacleIconData enabled;",
            "        ObstacleIconData disabled;",
            "    };",
            "",
            "    constexpr ObstacleIconPair kObstacleIcons[] =",
            "    {",
            *rows,
            "    };",
            "",
            "    struct ObstaclePreviewResource",
            "    {",
            "        int buttonIndex;",
            "        int resourceId;",
            "    };",
            "",
            "    constexpr ObstaclePreviewResource kObstaclePreviews[] =",
            "    {",
            *preview_rows,
            "    };",
            "}",
            "",
            "const ObstacleIconData* ObstacleIconForButton(int buttonIndex, bool enabled)",
            "{",
            "    for (const ObstacleIconPair& pair : kObstacleIcons)",
            "    {",
            "        if (pair.buttonIndex == buttonIndex)",
            "            return enabled ? &pair.enabled : &pair.disabled;",
            "    }",
            "    return nullptr;",
            "}",
            "",
            "int ObstaclePreviewResourceForButton(int buttonIndex)",
            "{",
            "    for (const ObstaclePreviewResource& preview : kObstaclePreviews)",
            "    {",
            "        if (preview.buttonIndex == buttonIndex)",
            "            return preview.resourceId;",
            "    }",
            "    return -1;",
            "}",
            "",
        ]
    )


def generate_preview_resources(previews: dict[int, Path], output: Path) -> str:
    lines = ["// Generated by tools/generate_obstacle_icons.py."]
    for number, path in sorted(previews.items()):
        relative_path = path.relative_to(output.parent).as_posix()
        lines.append(
            f'{PREVIEW_RESOURCE_BASE + number} RCDATA "{relative_path}"'
        )
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--icons",
        type=Path,
        default=Path("plugin/resources/obstacle_icons"),
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("plugin/obstacle_icon_data.cpp"),
    )
    parser.add_argument(
        "--preview-resources",
        type=Path,
        default=Path("plugin/obstacle_preview_resources.rc"),
    )
    args = parser.parse_args()

    icons = collect_icons(args.icons)
    if not icons:
        raise ValueError(f"No obstacle icons found under {args.icons}")

    previews = collect_previews(args.icons, icons)

    args.output.write_text(
        generate_source(icons, previews), encoding="ascii", newline="\n"
    )
    args.preview_resources.write_text(
        generate_preview_resources(previews, args.preview_resources),
        encoding="ascii",
        newline="\n",
    )
    print(
        f"Generated {args.output} with {len(icons)} enabled/disabled icon pairs "
        f"and {len(previews)} previews."
    )


if __name__ == "__main__":
    main()
