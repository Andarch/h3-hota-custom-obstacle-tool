"""Generate Unicode tables and the tester review list from translations/ru.json."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]

def generate(check=False):
    groups = json.loads((ROOT / "translations/ru.json").read_text(encoding="utf-8"))
    entries = {}
    lines = ["# Russian translation review", "", "Edit `translations/ru.json`, then run `python tools/generate_translations.py`.",
             "Edit only the Russian values; keep the English keys unchanged.",
             "These are draft translations for native-speaker review. Product names, filenames,", "keyboard shortcuts, DEF identifiers and diagnostic logs retain their original spelling.", ""]
    for group, strings in groups.items():
        lines += ["## " + group.capitalize(), "", "| English | Russian |", "| --- | --- |"]
        for english, russian in strings.items():
            if not russian.strip():
                raise ValueError("Empty translation: " + english)
            if english in entries and entries[english] != russian:
                raise ValueError("Conflicting translation: " + english)
            entries[english] = russian
            lines.append("| " + english.replace("\n", "<br>").replace("|", "&#124;") + " | " + russian.replace("\n", "<br>").replace("|", "&#124;") + " |")
        lines.append("")
    metadata = (ROOT / "plugin/obstacle_button_data.cpp").read_text(encoding="utf-8")
    buttons = re.search(r'kObstacleButtons\[\]\s*=\s*\{(.*?)\n    \};', metadata, re.S).group(1)
    names = re.findall(r'^        \{ "([^\"]+)"', buttons, re.M)
    categories = re.search(r'kObstacleCategoryNames\[\]\s*=\s*\{(.*?)\n    \};', metadata, re.S).group(1)
    category_names = re.findall(r'"([^\"]+)"', categories)
    for group, expected in (("obstacles", names), ("categories", category_names)):
        if set(groups[group]) != set(expected):
            raise ValueError("Translation coverage does not match " + group)
    rows = ["// Generated by tools/generate_translations.py; edit translations/ru.json."]
    for english, russian in entries.items():
        rows.append("    { " + json.dumps(english) + ", L" + json.dumps(english) + ", L" + json.dumps(russian) + " },")
    outputs = {ROOT / "shared/localization_strings.inc": "\n".join(rows) + "\n",
               ROOT / "docs/russian-translation-review.md": "\n".join(lines)}
    for path, text in outputs.items():
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                raise ValueError("Regenerate " + str(path.relative_to(ROOT)))
        else:
            path.write_text(text, encoding="utf-8")
    print(f"Validated {len(entries)} English/Russian strings, including {len(names)} obstacle buttons.")

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    generate(parser.parse_args().check)
